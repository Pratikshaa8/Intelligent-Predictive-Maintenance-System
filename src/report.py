from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether

def build_pdf_report(result, inputs):
    buf=BytesIO()
    doc=SimpleDocTemplate(buf,pagesize=A4,rightMargin=18*mm,leftMargin=18*mm,topMargin=16*mm,bottomMargin=16*mm)
    styles=getSampleStyleSheet()
    styles.add(ParagraphStyle(name="PMTitle",parent=styles["Title"],textColor=colors.HexColor("#17324d"),fontSize=20,leading=24,spaceAfter=5))
    styles.add(ParagraphStyle(name="PMSub",parent=styles["Normal"],textColor=colors.HexColor("#52708b"),fontSize=9,spaceAfter=12))
    styles.add(ParagraphStyle(name="PMHead",parent=styles["Heading2"],textColor=colors.HexColor("#176b70"),fontSize=12,spaceBefore=12,spaceAfter=6))
    story=[Paragraph("PM-CDSS | Maintenance Assessment",styles["PMTitle"]),
           Paragraph("Intelligent Predictive-Maintenance Decision Support System · Decision-support prototype",styles["PMSub"])]
    data=[["Risk level",result["risk_level"],"Fused risk",f'{result["risk_score"]:.1%}'],
          ["Diagnosis",result["diagnosis"],"Priority",result["priority"]],
          ["ML probability",f'{result["ml_probability"]:.1%}',"DL probability",f'{result["dl_probability"]:.1%}'],
          ["Expert score",f'{result["expert_score"]:.2f}',"Rule fired",result["rule_fired"]]]
    t=Table(data,colWidths=[32*mm,55*mm,32*mm,55*mm])
    t.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,-1),colors.HexColor("#edf4f7")),("GRID",(0,0),(-1,-1),.4,colors.HexColor("#c4d5df")),
                           ("FONTNAME",(0,0),(-1,-1),"Helvetica"),("FONTSIZE",(0,0),(-1,-1),9),("PADDING",(0,0),(-1,-1),7),
                           ("TEXTCOLOR",(0,0),(0,-1),colors.HexColor("#31516a")),("TEXTCOLOR",(2,0),(2,-1),colors.HexColor("#31516a"))]))
    story += [t,Paragraph("Sensor readings",styles["PMHead"])]
    sens=[["Input","Value"],["Product type",inputs["machine_type"]],["Air temperature",f'{inputs["air_temp"]} K'],
          ["Process temperature",f'{inputs["process_temp"]} K'],["Rotational speed",f'{inputs["speed"]} rpm'],
          ["Torque",f'{inputs["torque"]} Nm'],["Tool wear",f'{inputs["wear"]} min']]
    st=Table(sens,colWidths=[65*mm,90*mm])
    st.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,0),colors.HexColor("#17324d")),("TEXTCOLOR",(0,0),(-1,0),colors.white),
                            ("GRID",(0,0),(-1,-1),.4,colors.HexColor("#c4d5df")),("PADDING",(0,0),(-1,-1),6),("FONTSIZE",(0,0),(-1,-1),9)]))
    story += [st,Paragraph("Recommended maintenance response",styles["PMHead"]),
              Paragraph(result["recommendation"],styles["BodyText"]),
              Paragraph(f"<b>Suggested time window:</b> {result['time_window']}",styles["BodyText"]),
              Paragraph("Expert-system trace",styles["PMHead"])]
    for line in result["rule_trace"]: story.append(Paragraph("• "+line,styles["BodyText"]))
    story.append(Paragraph("Local feature impact (perturbation approximation)",styles["PMHead"]))
    fi=[["Feature","Impact"]]+[[k,f"{v:+.4f}"] for k,v in result["feature_impacts"]]
    ft=Table(fi,colWidths=[100*mm,55*mm])
    ft.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,0),colors.HexColor("#17324d")),("TEXTCOLOR",(0,0),(-1,0),colors.white),
                            ("GRID",(0,0),(-1,-1),.4,colors.HexColor("#c4d5df")),("PADDING",(0,0),(-1,-1),6),("FONTSIZE",(0,0),(-1,-1),8)]))
    story += [ft,Paragraph("Human approval required",styles["PMHead"]),
              Paragraph("This output is a decision-support recommendation, not an autonomous control command. A qualified maintenance engineer must inspect the equipment, verify operating limits and approve any intervention.",styles["BodyText"]),
              Spacer(1,8),Paragraph("Generated by the locally reconstructed PM-CDSS prototype.",styles["PMSub"])]
    doc.build(story)
    return buf.getvalue()
